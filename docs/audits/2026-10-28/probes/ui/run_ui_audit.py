#!/usr/bin/env python3
"""Build and run the read-only LVGL baseline and targeted UI audit probe.

Exit codes: 0 = no keyboard defect; 1 = known keyboard defect reproduced;
2 = build, baseline, sanitizer, environment, or unexpected probe failure.
This script uses only the Python standard library and local source files.
"""

from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys


HERE = Path(__file__).resolve().parent
DEFAULT_REPO = Path(__file__).resolve().parents[5]
KNOWN_KEYBOARD_FAILURES = {
    "FAIL switching to symbols must not type a character",
    "FAIL abc must return to lowercase without entering characters",
    "FAIL direct lowercase-to-symbol switch inserted text",
}
SANITIZER_MARKERS = (
    "AddressSanitizer:",
    "ERROR: LeakSanitizer:",
    "LeakSanitizer has encountered",
    "UndefinedBehaviorSanitizer:",
    "runtime error:",
)


class AuditError(Exception):
    """An error distinct from a deliberately reproduced product defect."""


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--repo", type=Path, default=DEFAULT_REPO,
        help="boiler_room checkout root; defaults to this script's repository root",
    )
    parser.add_argument(
        "--lvgl", type=Path, required=True,
        help="unpacked LVGL 8.3.11 source directory from the native Actions artifact",
    )
    parser.add_argument(
        "--output", type=Path, required=True,
        help="separate temporary output directory for objects, executables, logs and PPMs",
    )
    parser.add_argument("--jobs", type=int, default=min(os.cpu_count() or 2, 6))
    parser.add_argument("--timeout", type=int, default=120,
                        help="timeout in seconds for each compiler or test process")
    parser.add_argument("--baseline-only", action="store_true",
                        help="build and run only the original host baseline (success exits 0)")
    parser.add_argument("--cc", default="gcc", help="C compiler (default: gcc)")
    parser.add_argument("--cxx", default="g++", help="C++ compiler (default: g++)")
    parser.add_argument("--ar", default="ar", help="static archiver (default: ar)")
    args = parser.parse_args()
    if not 1 <= args.jobs <= 64:
        parser.error("--jobs must be between 1 and 64")
    if args.timeout <= 0:
        parser.error("--timeout must be positive")
    args.repo = args.repo.expanduser().resolve()
    args.lvgl = args.lvgl.expanduser().resolve()
    args.output = args.output.expanduser().resolve()
    return args


def is_inside(path: Path, parent: Path) -> bool:
    try:
        path.relative_to(parent)
        return True
    except ValueError:
        return False


def validate(args: argparse.Namespace) -> None:
    for source in (
        "src/main.cpp", "src/panel_screen.cpp", "src/panel_types.h",
        "src/screen_state.h", "src/boiler_fonts.c", "tests/host/host.cpp",
        "tests/host/lv_conf.h", "tests/host/stubs/Arduino.h",
    ):
        if not (args.repo / source).is_file():
            raise AuditError(f"Missing source file: {args.repo / source}")
    if not (HERE / "ui_probe.cpp").is_file():
        raise AuditError("ui_probe.cpp must be next to this runner")
    header = args.lvgl / "lvgl.h"
    if not header.is_file() or not (args.lvgl / "src").is_dir():
        raise AuditError("--lvgl must point to the unpacked LVGL source root")
    version_source = header.read_text(encoding="utf-8")
    version = []
    for key in ("MAJOR", "MINOR", "PATCH"):
        match = re.search(r"^\s*#define\s+LVGL_VERSION_" + key + r"\s+(\d+)",
                          version_source, re.MULTILINE)
        if not match:
            raise AuditError(f"Cannot read LVGL_VERSION_{key} from lvgl.h")
        version.append(int(match.group(1)))
    if tuple(version) != (8, 3, 11):
        raise AuditError(f"LVGL 8.3.11 is required; found {'.'.join(map(str, version))}")
    # Keep every generated byte out of the audited repository and the dependency.
    if is_inside(args.output, args.repo) or is_inside(args.output, args.lvgl):
        raise AuditError("--output must be outside --repo and --lvgl")
    if args.output == args.output.parent:
        raise AuditError("--output cannot be the filesystem root")
    for option in ("cc", "cxx", "ar"):
        executable = shutil.which(getattr(args, option))
        if not executable:
            raise AuditError(f"Compiler/tool not found: {getattr(args, option)}")
        setattr(args, option, executable)


def run_process(command: list[str], cwd: Path, timeout: int,
                env: dict[str, str] | None = None) -> subprocess.CompletedProcess:
    try:
        return subprocess.run(command, cwd=cwd, env=env, timeout=timeout,
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                              text=True, errors="replace", check=False)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise AuditError(f"Could not complete {command[0]}: {exc}") from exc


def build(args: argparse.Namespace) -> tuple[Path, Path | None]:
    build_dir = args.output / "build"
    obj_dir = build_dir / "obj"
    obj_dir.mkdir(parents=True, exist_ok=True)
    config = args.repo / "tests/host/lv_conf.h"
    common = [
        "-O1", "-g", "-fsanitize=address,undefined", "-fno-omit-frame-pointer",
        "-I" + str(args.lvgl), "-I" + str(args.repo / "tests/host"),
        "-I" + str(args.repo / "tests/host/stubs"), "-I" + str(args.repo / "src"),
        "-DLV_CONF_PATH=" + str(config),
    ]
    sources = sorted((args.lvgl / "src").rglob("*.c"))
    if not sources:
        raise AuditError("No LVGL C source files found")
    print(f"BUILD: {len(sources)} LVGL C files, ASan + UBSan, {args.jobs} workers", flush=True)
    log_path = args.output / "build.log"
    with log_path.open("w", encoding="utf-8") as log:
        def compile_lvgl(source: Path):
            obj = obj_dir / "lvgl" / (str(source.relative_to(args.lvgl)) + ".o")
            obj.parent.mkdir(parents=True, exist_ok=True)
            command = [args.cc, "-std=c99", *common, "-c", str(source), "-o", str(obj)]
            result = run_process(command, build_dir, args.timeout)
            return obj, command, result

        objects = []
        errors = []
        with ThreadPoolExecutor(max_workers=args.jobs) as pool:
            futures = [pool.submit(compile_lvgl, source) for source in sources]
            for future in as_completed(futures):
                obj, command, result = future.result()
                log.write(json.dumps(command) + "\n" + result.stdout)
                if result.returncode:
                    errors.append((command, result.returncode))
                objects.append(obj)
        if errors:
            raise AuditError(f"{len(errors)} LVGL compile command(s) failed; see {log_path}")

        def checked(command: list[str]) -> None:
            result = run_process(command, build_dir, args.timeout)
            log.write(json.dumps(command) + "\n" + result.stdout)
            log.flush()
            if result.returncode:
                raise AuditError(f"Build command failed with exit {result.returncode}; see {log_path}")

        archive = build_dir / "liblvgl.a"
        checked([args.ar, "rcs", str(archive), *map(str, sorted(objects))])
        fonts, screen = obj_dir / "boiler_fonts.o", obj_dir / "panel_screen.o"
        checked([args.cc, "-std=c99", *common, "-c", str(args.repo / "src/boiler_fonts.c"),
                 "-o", str(fonts)])
        checked([args.cxx, "-std=c++17", *common, "-c", str(args.repo / "src/panel_screen.cpp"),
                 "-o", str(screen)])
        executables = []
        targets = [("baseline_asan", args.repo / "tests/host/host.cpp")]
        if not args.baseline_only:
            targets.append(("ui_probe_asan", HERE / "ui_probe.cpp"))
        for name, source in targets:
            executable = build_dir / name
            checked([args.cxx, "-std=c++17", *common, str(source), str(screen), str(fonts),
                     str(archive), "-lm", "-o", str(executable)])
            executables.append(executable)
    print(f"BUILD: {len(executables)} executable(s) built", flush=True)
    return executables[0], executables[1] if len(executables) > 1 else None


def run_test(args: argparse.Namespace, executable: Path, name: str) -> tuple[int, str]:
    directory = args.output / name
    directory.mkdir(parents=True, exist_ok=True)
    env = os.environ.copy()
    # LeakSanitizer cannot run in some ptraced/container environments. This audit
    # checks ASan/UBSan diagnostics but deliberately makes no leak-check claim.
    env["ASAN_OPTIONS"] = "detect_leaks=0:halt_on_error=1"
    env["UBSAN_OPTIONS"] = "halt_on_error=1:print_stacktrace=1"
    result = run_process([str(executable)], directory, args.timeout, env)
    (directory / f"{name}.log").write_text(result.stdout, encoding="utf-8")
    return result.returncode, result.stdout


def check_sanitizers(output: str, test: str) -> None:
    if any(marker in output for marker in SANITIZER_MARKERS):
        raise AuditError(f"SANITIZER ERROR in {test}; see its log. This is not a keyboard reproduction.")


def write_summary(args: argparse.Namespace, summary: dict) -> None:
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    args = parse_args()
    summary = {"lvgl": "8.3.11", "leak_check": False, "status": "not_run"}
    validated = False
    try:
        validate(args)
        validated = True
        args.output.mkdir(parents=True, exist_ok=True)
        summary["inputs_sha256"] = {
            source: hashlib.sha256((args.repo / source).read_bytes()).hexdigest()
            for source in ("src/main.cpp", "src/panel_types.h", "src/screen_state.h",
                           "src/panel_screen.cpp", "src/boiler_fonts.c", "tests/host/host.cpp",
                           "tests/host/lv_conf.h")
        }
        baseline, probe = build(args)
        baseline_code, baseline_output = run_test(args, baseline, "baseline")
        summary["baseline_exit_code"] = baseline_code
        check_sanitizers(baseline_output, "baseline")
        if baseline_code != 0:
            raise AuditError(f"BASELINE FAILED with exit {baseline_code}; probe was not run")
        print("BASELINE PASS: exit 0; no ASan/UBSan diagnostics", flush=True)
        if args.baseline_only:
            summary["status"] = "baseline_pass"
            write_summary(args, summary)
            print(f"Baseline evidence and summary: {args.output}", flush=True)
            return 0
        if probe is None:
            raise AuditError("Probe executable was not built")

        probe_code, probe_output = run_test(args, probe, "probes")
        summary["probe_exit_code"] = probe_code
        check_sanitizers(probe_output, "probes")
        failures = [line for line in probe_output.splitlines() if line.startswith("FAIL ")]
        completion = re.findall(r"^COMPLETE targeted UI probes; behavior failures=(\d+)$",
                                probe_output, re.MULTILINE)
        if len(completion) != 1:
            raise AuditError(f"Probe did not finish normally (exit {probe_code}); see probes/probes.log")
        count = int(completion[0])
        summary["keyboard_failures"] = failures
        if (probe_code == 1 and 1 <= count <= len(KNOWN_KEYBOARD_FAILURES)
                and count == len(failures) == len(set(failures))
                and set(failures).issubset(KNOWN_KEYBOARD_FAILURES)):
            summary["status"] = "defect_reproduced"
            write_summary(args, summary)
            print(f"DEFECT REPRODUCED: {count} known keyboard checks failed; probe exit 1", flush=True)
            print("Baseline passed. This is a product-behavior result, not a compile/sanitizer error.", flush=True)
            print(f"Evidence and summary: {args.output}", flush=True)
            return 1
        if probe_code == 0 and count == 0 and not failures:
            summary["status"] = "no_keyboard_defect_reproduced"
            write_summary(args, summary)
            print("PROBE PASS: exit 0; known keyboard defect not reproduced", flush=True)
            print(f"Evidence and summary: {args.output}", flush=True)
            return 0
        raise AuditError(f"Unexpected probe result: exit={probe_code}, reported failures={count}")
    except (AuditError, OSError) as exc:
        summary["status"] = "audit_error"
        summary["error"] = str(exc)
        # Do not write anything before input paths have passed validation.
        if validated and args.output.is_dir():
            try:
                write_summary(args, summary)
            except OSError:
                pass
        print(f"AUDIT ERROR: {exc}", file=sys.stderr, flush=True)
        return 2


if __name__ == "__main__":
    sys.exit(main())
